CREATE TABLE sesion (
  sesion_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planeacion_id BIGINT NOT NULL REFERENCES planeacion(planeacion_id),
  parcial_id    BIGINT NOT NULL REFERENCES parcial(parcial_id),
  horario_id    BIGINT REFERENCES horario_asignacion(horario_id),
  fecha         DATE NOT NULL,
  proposito     TEXT,
  estado        VARCHAR(25) NOT NULL DEFAULT 'Programada',
  creado_por    BIGINT NOT NULL REFERENCES usuario(usuario_id),
  creado_en     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_sesion_fecha ON sesion(fecha);

CREATE TABLE concrecion (
  concrecion_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sesion_id            BIGINT NOT NULL UNIQUE REFERENCES sesion(sesion_id),
  descripcion_planeado TEXT,
  descripcion_observado TEXT,
  reflexion            TEXT,
  estado               VARCHAR(25) NOT NULL DEFAULT 'En captura',
  actualizado_por      BIGINT REFERENCES usuario(usuario_id),
  actualizado_en       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_concrecion_touch BEFORE UPDATE ON concrecion
  FOR EACH ROW EXECUTE FUNCTION f_touch_actualizado();

