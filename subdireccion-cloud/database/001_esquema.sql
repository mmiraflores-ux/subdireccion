-- ---------------------------------------------------------------------
-- Vista: planeaciones esperadas por asignación y parcial
-- ---------------------------------------------------------------------
CREATE VIEW vw_planeaciones_por_asignacion AS
SELECT aa.asignacion_id,
       p.nombre            AS docente,
       g.identificador     AS grupo,
       uc.nombre_oficial   AS unidad_curricular,
       aa.ciclo_id,
       aa.periodo_id,
       pa.parcial_id,
       pa.numero           AS numero_parcial,
       pa.fecha_inicio,
       pa.fecha_fin,
       pa.fecha_evaluacion,
       pl.planeacion_id,
       pl.nombre_archivo,
       pl.estado           AS estado_planeacion,
       pl.resultado_revision,
       pl.es_vigente
FROM asignacion_academica aa
JOIN persona p            ON p.persona_id = aa.docente_persona_id
JOIN grupo g              ON g.grupo_id = aa.grupo_id
JOIN unidad_curricular uc ON uc.unidad_curricular_id = aa.unidad_curricular_id
JOIN parcial pa           ON pa.periodo_id = aa.periodo_id
LEFT JOIN planeacion pl   ON pl.asignacion_id = aa.asignacion_id
                         AND pl.parcial_id = pa.parcial_id
                         AND pl.es_vigente
WHERE aa.estado = 'Vigente';
