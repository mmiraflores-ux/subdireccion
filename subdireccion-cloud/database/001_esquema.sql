CREATE EXTENSION IF NOT EXISTS unaccent;

-- Función inmutable para búsquedas sin acentos ni mayúsculas
CREATE OR REPLACE FUNCTION f_normaliza(txt text) RETURNS text
LANGUAGE sql STABLE PARALLEL SAFE AS
$$ SELECT lower(unaccent(coalesce(txt, ''))) $$;

CREATE OR REPLACE FUNCTION f_touch_actualizado() RETURNS trigger
LANGUAGE plpgsql AS
$$ BEGIN NEW.actualizado_en := now(); RETURN NEW; END $$;

-- ---------------------------------------------------------------------
-- Catálogos institucionales
-- ---------------------------------------------------------------------
CREATE TABLE ciclo_escolar (
  ciclo_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(20) NOT NULL UNIQUE,
  estado        VARCHAR(20) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE periodo_institucional (
  periodo_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ciclo_id      BIGINT NOT NULL REFERENCES ciclo_escolar(ciclo_id),
  codigo        VARCHAR(10) NOT NULL,
  nombre        VARCHAR(30) NOT NULL,
  fecha_inicio  DATE,
  fecha_fin     DATE,
  CONSTRAINT uq_periodo UNIQUE (ciclo_id, codigo)
);

CREATE TABLE parcial (
  parcial_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo_id       BIGINT NOT NULL REFERENCES periodo_institucional(periodo_id),
  numero           SMALLINT NOT NULL CHECK (numero BETWEEN 1 AND 9),
  fecha_inicio     DATE,
  fecha_fin        DATE,
  fecha_evaluacion DATE,
  CONSTRAINT uq_parcial UNIQUE (periodo_id, numero)
);

CREATE TABLE semestre_academico (
  semestre_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero        SMALLINT NOT NULL UNIQUE CHECK (numero BETWEEN 1 AND 12),
  nombre        VARCHAR(30) NOT NULL
);

CREATE TABLE grado (
  grado_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE grupo (
  grupo_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ciclo_id      BIGINT NOT NULL REFERENCES ciclo_escolar(ciclo_id),
  semestre_id   BIGINT NOT NULL REFERENCES semestre_academico(semestre_id),
  grado_id      BIGINT NOT NULL REFERENCES grado(grado_id),
  carrera       VARCHAR(120) NOT NULL,
  turno         VARCHAR(30),
  identificador VARCHAR(20) NOT NULL,
  CONSTRAINT uq_grupo UNIQUE (ciclo_id, identificador)
);

CREATE TABLE modelo_educativo (
  modelo_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo        VARCHAR(20) NOT NULL UNIQUE,
  nombre        VARCHAR(100) NOT NULL,
  estado        VARCHAR(20) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE version_curricular (
  version_curricular_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  modelo_id         BIGINT NOT NULL REFERENCES modelo_educativo(modelo_id),
  nombre            VARCHAR(150) NOT NULL,
  fecha_inicio      DATE,
  fecha_fin         DATE,
  fuente_referencia TEXT,
  estado            VARCHAR(20) NOT NULL DEFAULT 'Activa'
);

CREATE TABLE unidad_curricular (
  unidad_curricular_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_curricular_id BIGINT NOT NULL REFERENCES version_curricular(version_curricular_id),
  tipo_unidad       VARCHAR(30) NOT NULL,
  nombre_oficial    VARCHAR(250) NOT NULL,
  codigo_curricular VARCHAR(50),
  estado            VARCHAR(20) NOT NULL DEFAULT 'Activa'
);

-- ---------------------------------------------------------------------
-- Personas, usuarios y roles
-- ---------------------------------------------------------------------
CREATE TABLE persona (
  persona_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomenclatura  VARCHAR(50) UNIQUE,
  nombre        VARCHAR(180) NOT NULL,
  estado        VARCHAR(20) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE usuario (
  usuario_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id          BIGINT NOT NULL UNIQUE REFERENCES persona(persona_id),
  identificador_login VARCHAR(150) NOT NULL UNIQUE,
  hash_credencial     VARCHAR(255),
  estado              VARCHAR(20) NOT NULL DEFAULT 'Activo',
  creado_en           TIMESTAMPTZ NOT NULL DEFAULT now(),
  debe_cambiar_contrasena BOOLEAN NOT NULL DEFAULT FALSE,
  ultimo_acceso       TIMESTAMPTZ
);

CREATE TABLE rol (
  rol_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo        VARCHAR(40) NOT NULL UNIQUE,
  nombre        VARCHAR(100) NOT NULL,
  descripcion   TEXT,
  estado        VARCHAR(20) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE usuario_rol (
  usuario_rol_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id     BIGINT NOT NULL REFERENCES usuario(usuario_id),
  rol_id         BIGINT NOT NULL REFERENCES rol(rol_id),
  ciclo_id       BIGINT REFERENCES ciclo_escolar(ciclo_id),
  fecha_inicio   DATE NOT NULL,
  fecha_fin      DATE,
  estado         VARCHAR(20) NOT NULL DEFAULT 'Activo'
);
CREATE INDEX idx_usuario_rol_usuario ON usuario_rol(usuario_id);

-- ---------------------------------------------------------------------
-- Asignación académica
-- ---------------------------------------------------------------------
CREATE TABLE asignacion_academica (
  asignacion_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grupo_id             BIGINT NOT NULL REFERENCES grupo(grupo_id),
  unidad_curricular_id BIGINT NOT NULL REFERENCES unidad_curricular(unidad_curricular_id),
  docente_persona_id   BIGINT NOT NULL REFERENCES persona(persona_id),
  ciclo_id             BIGINT NOT NULL REFERENCES ciclo_escolar(ciclo_id),
  periodo_id           BIGINT NOT NULL REFERENCES periodo_institucional(periodo_id),
  fecha_inicio         DATE,
  fecha_fin            DATE,
  estado               VARCHAR(25) NOT NULL DEFAULT 'Propuesta'
);
CREATE INDEX idx_asig_grupo ON asignacion_academica(grupo_id);
CREATE INDEX idx_asig_docente ON asignacion_academica(docente_persona_id);

CREATE TABLE horario_asignacion (
  horario_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asignacion_id BIGINT NOT NULL REFERENCES asignacion_academica(asignacion_id),
  dia_semana    SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio   TIME NOT NULL,
  hora_fin      TIME NOT NULL,
  espacio       VARCHAR(100)
);

-- ---------------------------------------------------------------------
-- Planeaciones
-- ---------------------------------------------------------------------
CREATE TABLE planeacion (
  planeacion_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asignacion_id          BIGINT NOT NULL REFERENCES asignacion_academica(asignacion_id),
  parcial_id             BIGINT REFERENCES parcial(parcial_id),
  tipo_documento         VARCHAR(10) NOT NULL DEFAULT 'PARCIAL'
                         CHECK (tipo_documento IN ('SEMESTRAL','PARCIAL')),
  planeacion_anterior_id BIGINT REFERENCES planeacion(planeacion_id),
  nombre_archivo         VARCHAR(255) NOT NULL,
  archivo_original_uri   TEXT NOT NULL,
  motivo_correccion      TEXT,
  estado                 VARCHAR(25) NOT NULL DEFAULT 'Cargada',
  resultado_revision     VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
  es_vigente             BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_carga            TIMESTAMPTZ NOT NULL DEFAULT now(),
  usuario_carga          BIGINT NOT NULL REFERENCES usuario(usuario_id),
  fecha_revision         TIMESTAMPTZ,
  usuario_revision       BIGINT REFERENCES usuario(usuario_id),
  CONSTRAINT ck_planeacion_tipo_parcial CHECK (
    (tipo_documento = 'SEMESTRAL' AND parcial_id IS NULL) OR
    (tipo_documento = 'PARCIAL'   AND parcial_id IS NOT NULL))
);
CREATE INDEX idx_planeacion_asig_parcial ON planeacion(asignacion_id, parcial_id);

-- Contenido del PDF (separado para que las consultas de listado sean ligeras)
CREATE TABLE planeacion_archivo (
  planeacion_id  BIGINT PRIMARY KEY REFERENCES planeacion(planeacion_id) ON DELETE CASCADE,
  tamano_bytes   BIGINT NOT NULL,
  contenido      BYTEA NOT NULL
);

-- Prevención de duplicados por huella SHA-256
CREATE TABLE planeacion_archivo_hash (
  planeacion_hash_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planeacion_id      BIGINT NOT NULL REFERENCES planeacion(planeacion_id) ON DELETE CASCADE,
  sha256             CHAR(64) NOT NULL,
  fecha_registro     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_planeacion_archivo_hash_sha256 UNIQUE (sha256)
);
CREATE INDEX idx_planeacion_hash_planeacion ON planeacion_archivo_hash(planeacion_id);

-- Lote de carga masiva en espera de confirmación
CREATE TABLE carga_pendiente (
  carga_pendiente_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lote_id        CHAR(32) NOT NULL,
  usuario_id     BIGINT NOT NULL REFERENCES usuario(usuario_id),
  orden          INTEGER NOT NULL,
  nombre_original VARCHAR(255) NOT NULL,
  ruta_relativa  TEXT,
  sha256         CHAR(64) NOT NULL,
  tamano_bytes   BIGINT NOT NULL,
  contenido      BYTEA NOT NULL,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_carga_pendiente UNIQUE (lote_id, orden)
);
CREATE INDEX idx_carga_pendiente_creado ON carga_pendiente(creado_en);

-- ---------------------------------------------------------------------
